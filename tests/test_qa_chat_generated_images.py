"""QA: a generated image shows up in the chat without the model saying so.

`/api/chats/{id}/file?path=...` already served any image in a chat's own
workspace, and the chat renderer already turned a markdown image link into a
clickable chip -- both existed before this file. What was missing was
detection: whether a screenshot the agent left on disk ever became visible in
the chat depended entirely on the model's own prose happening to name it as a
markdown link or a recognisable bare path. A turn that wrote a file and said
only "I made a screenshot" left nothing for the renderer to find.

`_new_workspace_images` closes that gap by mtime rather than by wording: any
image file under the chat's own work_dir newer than when the turn started is
treated as generated by this turn, appended to the stored assistant message as
a markdown image link, and rendered through the existing chip mechanism with
no new route and no new frontend code.
"""
from __future__ import annotations

import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

import config
import db
from routes import chats as chat_routes


def _events(*texts: str, write=None):
    """A fake `runner.stream_turn`. *write*, if given, runs mid-stream --
    the file must appear *during* the turn, the same as a real agent writing
    it, or its mtime would predate the turn's own start_ts and the scan would
    (correctly) treat it as pre-existing rather than generated.
    """
    async def gen():
        if write is not None:
            write()
        for text in texts:
            yield {"type": "text", "content": text}
        yield {"type": "done"}
    return gen


class NewWorkspaceImagesQA(unittest.TestCase):
    """Unit: which files on disk count as "generated by this turn"."""

    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)

    def _touch(self, rel: str, mtime: float) -> Path:
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(b"x")
        import os
        os.utime(path, (mtime, mtime))
        return path

    def test_a_file_older_than_the_cutoff_is_not_generated(self):
        self._touch("old.png", mtime=100.0)
        self.assertEqual(
            chat_routes._new_workspace_images(str(self.root), since=200.0), []
        )

    def test_a_file_newer_than_the_cutoff_is_found(self):
        self._touch("new.png", mtime=300.0)
        self.assertEqual(
            chat_routes._new_workspace_images(str(self.root), since=200.0),
            ["new.png"],
        )

    def test_a_non_image_file_is_ignored_even_if_new(self):
        self._touch("notes.txt", mtime=300.0)
        self.assertEqual(
            chat_routes._new_workspace_images(str(self.root), since=200.0), []
        )

    def test_a_subdirectory_image_is_found_with_a_relative_path(self):
        self._touch("shots/one.png", mtime=300.0)
        self.assertEqual(
            chat_routes._new_workspace_images(str(self.root), since=200.0),
            ["shots/one.png"],
        )

    def test_skip_directories_are_never_walked(self):
        self._touch("node_modules/pkg/icon.png", mtime=300.0)
        self.assertEqual(
            chat_routes._new_workspace_images(str(self.root), since=200.0), []
        )

    def test_hidden_directories_are_never_walked(self):
        self._touch(".git/objects/thing.png", mtime=300.0)
        self.assertEqual(
            chat_routes._new_workspace_images(str(self.root), since=200.0), []
        )

    def test_results_are_capped_and_oldest_first(self):
        for n in range(chat_routes._GENERATED_IMAGE_MAX + 3):
            self._touch(f"shot-{n}.png", mtime=300.0 + n)
        found = chat_routes._new_workspace_images(str(self.root), since=200.0)
        self.assertEqual(len(found), chat_routes._GENERATED_IMAGE_MAX)
        self.assertEqual(found, sorted(found))
        self.assertEqual(found[0], "shot-0.png")


class TurnAppendsGeneratedImagesQA(unittest.IsolatedAsyncioTestCase):
    """Component: a real turn through `_start_turn` picks up a new image."""

    async def asyncSetUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.db_patch = patch.object(config, "DB_PATH", f"{self.tmp.name}/db")
        self.root_patch = patch.object(
            config, "PROJECTS_ROOT", f"{self.tmp.name}/projects")
        self.db_patch.start()
        self.root_patch.start()
        await db.init()
        self.work = Path(config.PROJECTS_ROOT) / "w"
        self.work.mkdir(parents=True)
        self.chat_id = "g" * 32
        await db.chat_create(self.chat_id, "cweb-img", None, str(self.work), "admin")

    async def asyncTearDown(self):
        await db.close()
        self.db_patch.stop()
        self.root_patch.stop()
        self.tmp.cleanup()

    async def _run(self, event_gen):
        import runner
        chat = await db.chat_get(self.chat_id, "admin")
        with patch.object(runner, "stream_turn", lambda *a, **k: event_gen()):
            turn = await chat_routes._start_turn(chat, "admin", "make a chart", None)
            await turn.task
        rows = await db.messages_get(self.chat_id)
        return [m for m in rows if m["role"] == "assistant"][-1]["content"]

    async def test_an_image_written_during_the_turn_is_appended(self):
        write = lambda: (self.work / "chart.png").write_bytes(b"x")
        content = await self._run(_events("Here is the result.", write=write))
        self.assertIn("Here is the result.", content)
        self.assertIn("![chart.png](chart.png)", content)

    async def test_a_pre_existing_image_is_not_re_attached(self):
        """Otherwise every later turn in the chat re-announces the same file."""
        import os
        old = self.work / "logo.png"
        old.write_bytes(b"x")
        os.utime(old, (1_000_000.0, 1_000_000.0))
        content = await self._run(_events("Done."))
        self.assertNotIn("logo.png", content)

    async def test_no_image_means_no_extra_markup(self):
        content = await self._run(_events("Just text, nothing generated."))
        self.assertEqual(content, "Just text, nothing generated.")

    async def test_an_image_with_no_text_answer_is_still_kept(self):
        """A turn that only produced a file must not be discarded as empty."""
        write = lambda: (self.work / "only.png").write_bytes(b"x")
        content = await self._run(_events(write=write))
        self.assertIn("![only.png](only.png)", content)

    async def test_a_generated_image_is_recorded_in_the_gallery_table(self):
        write = lambda: (self.work / "chart.png").write_bytes(b"x")
        await self._run(_events("Here is the result.", write=write))
        rows, _, _ = await db.generated_images_list("admin")
        self.assertEqual(len(rows), 1)
        self.assertEqual(rows[0]["path"], "chart.png")
        self.assertEqual(rows[0]["chat_id"], self.chat_id)
        self.assertEqual(rows[0]["chat_title"], "cweb-img")

    async def test_a_pre_existing_image_is_not_recorded_either(self):
        """Same boundary as the markdown-append behaviour above: only
        images newer than the turn's own start count as generated."""
        import os
        old = self.work / "logo.png"
        old.write_bytes(b"x")
        os.utime(old, (1_000_000.0, 1_000_000.0))
        await self._run(_events("Done."))
        rows, _, _ = await db.generated_images_list("admin")
        self.assertEqual(rows, [])


if __name__ == "__main__":
    unittest.main()
